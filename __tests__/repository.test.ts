import { LoanRepository, IDatabaseDriver } from '../src/database/repository';

// In-Memory SQLite driver mock for unit & integration testing
class InMemoryTestDatabase implements IDatabaseDriver {
  private tables: {
    contacts: any[];
    loans: any[];
    installments: any[];
    payments: any[];
  } = {
    contacts: [],
    loans: [],
    installments: [],
    payments: [],
  };

  async execAsync(sql: string): Promise<void> {
    // schema initialization dummy
  }

  async runAsync(sql: string, params: any[] = []): Promise<{ lastInsertRowId?: number; changes?: number }> {
    const normalized = sql.replace(/\s+/g, ' ');
    if (normalized.includes('INSERT INTO contacts')) {
      const [id, full_name, phone, document_id, notes, created_at, updated_at] = params;
      this.tables.contacts.push({ id, full_name, phone, document_id, notes, created_at, updated_at });
      return { changes: 1 };
    }
    if (normalized.includes('INSERT INTO loans')) {
      const [
        id, contact_id, principal_cop, interest_type, interest_rate_basis_points,
        frequency, total_installments, start_date, due_date, status, notes, created_at, updated_at
      ] = params;
      this.tables.loans.push({
        id, contact_id, principal_cop, interest_type, interest_rate_basis_points,
        frequency, total_installments, start_date, due_date, status, notes, created_at, updated_at
      });
      return { changes: 1 };
    }
    if (normalized.includes('INSERT INTO installments')) {
      const [id, loan_id, installment_number, due_date, expected_amount_cop, status] = params;
      this.tables.installments.push({
        id, loan_id, installment_number, due_date, expected_amount_cop, status
      });
      return { changes: 1 };
    }
    return { changes: 0 };
  }

  async getAllAsync<T = any>(sql: string, params: any[] = []): Promise<T[]> {
    const normalized = sql.replace(/\s+/g, ' ');
    if (normalized.includes('FROM loans l JOIN contacts c')) {
      return this.tables.loans.map((l) => {
        const contact = this.tables.contacts.find((c) => c.id === l.contact_id);
        return {
          ...l,
          full_name: contact?.full_name || 'Desconocido',
          phone: contact?.phone || '',
        } as unknown as T;
      });
    }
    if (normalized.includes("FROM installments WHERE loan_id = ? AND status = 'PENDING'")) {
      const loanId = params[0];
      return this.tables.installments.filter(
        (i) => i.loan_id === loanId && i.status === 'PENDING'
      ) as unknown as T[];
    }
    if (normalized.includes('FROM installments WHERE loan_id = ?')) {
      const loanId = params[0];
      return this.tables.installments.filter((i) => i.loan_id === loanId) as unknown as T[];
    }
    return [];
  }

  async getFirstAsync<T = any>(sql: string, params: any[] = []): Promise<T | null> {
    const list = await this.getAllAsync<T>(sql, params);
    return list.length > 0 ? list[0] : null;
  }

  async withTransactionAsync<T>(callback: () => Promise<T>): Promise<T> {
    return await callback();
  }
}

describe('LoanRepository (Relational Database Operations)', () => {
  let db: InMemoryTestDatabase;
  let repo: LoanRepository;

  beforeEach(() => {
    db = new InMemoryTestDatabase();
    repo = new LoanRepository(db);
  });

  it('creates contact and daily loan with autogenerated installments', async () => {
    // 1. Create Borrower
    const contact = await repo.createContact({
      id: 'contact_123',
      fullName: 'Javier Rodríguez',
      phone: '+57 311 000 0000',
    });
    expect(contact.fullName).toBe('Javier Rodríguez');

    // 2. Disburse Daily Loan: $1.000.000 COP for 20 days at 20%
    const { loan, installments } = await repo.createDailyLoan({
      loanId: 'loan_456',
      contactId: contact.id,
      principalCOP: 1000000,
      rateBasisPoints: 2000,
      days: 20,
      startDate: new Date('2026-10-20'),
      notes: 'Ruta centro Ocaña',
    });

    expect(loan.id).toBe('loan_456');
    expect(loan.principalCOP).toBe(1000000);
    expect(loan.totalInstallments).toBe(20);
    expect(installments).toHaveLength(20);
    expect(installments[0].expectedAmountCOP).toBe(60000);

    // 3. Query all loans with joined borrower data
    const activeList = await repo.getAllLoansWithBorrower();
    expect(activeList).toHaveLength(1);
    expect(activeList[0].borrowerName).toBe('Javier Rodríguez');
    expect(activeList[0].totalDueCOP).toBe(1200000);
    expect(activeList[0].pendingAmountCOP).toBe(1200000);
  });
});
